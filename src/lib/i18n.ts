export const DEFAULT_LOCALE: Locale = 'nl';
export const LANG_KEY = 'overdracht-lang';
export const LANG_PARAM = 'lang';

export function isLocale(v: unknown): v is Locale {
  return typeof v === 'string' && (v === 'nl' || v === 'en');
}
export function defaultLocale(): Locale {
  return DEFAULT_LOCALE;
}
export function storedLocale(): Locale {
  if (typeof localStorage === 'undefined') return DEFAULT_LOCALE;
  try { return isLocale(localStorage.getItem(LANG_KEY)) ? localStorage.getItem(LANG_KEY)! : DEFAULT_LOCALE; } catch { return DEFAULT_LOCALE; }
}
export function localeFromSearch(search: string): Locale | undefined {
  const m = new URLSearchParams(search).get(LANG_PARAM);
  return isLocale(m) ? m : undefined;
}


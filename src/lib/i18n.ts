export function t(locale: Locale, key: string, params?: Record<string,string|number>, fallback?: string): string {
  let s=DICTIONARIES[locale]?.[key] ?? fallback ?? key;
  if(params)for(const [k,v]of Object.entries(params))s=s.replace(new RegExp('{'+k+'}','g'),String(v));
  return s;
}

interface LocaleState {
  locale: Locale;
  setLocale: Dispatch<Locale>;
}
export const LocaleContext = createContext<LocaleState | null>(null);

export function useTranslation() {
  const ctx = useContext(LocaleContext);
  const locale = ctx?.locale ?? DEFAULT_LOCALE;
  const tr = useCallback((key: string, params?: Record<string,string|number>, fallback?: string) => t(locale, key, params, fallback), [locale]);
  return { t: tr, locale, setLocale: ctx?.setLocale };
}
